#!/usr/bin/env python3
"""Export the Mac renderer's measured tables and bitmap fonts, without redrawing.

The independent guest captures remain test fixtures, never shipping assets.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def export():
    tables = {}
    for name in ["MeasuredChrome.swift", "MeasuredWindowChrome.swift"]:
        source = (ROOT / "app/Sources/PlatinumKit/Core" / name).read_text()
        for match in re.finditer(r"static let (\w+)(?:[^=\n]*)= \[", source):
            start = match.end() - 1
            depth = 1
            end = start + 1
            while depth:
                depth += (source[end] == "[") - (source[end] == "]")
                end += 1
            literal = source[start:end]
            if re.search(r'"[\w-]+":', literal):
                value = json.loads("{" + literal[1:-1].rstrip().rstrip(",") + "}")
            else:
                value = json.loads(re.sub(r",\s*]", "]", literal.replace("(", "[").replace(")", "]")))
            tables[match[1]] = value
    fonts = {}
    for key, name in [("system", "System-12"), ("regular", "Regular-12"), ("small", "Small-10")]:
        source = (ROOT / "platinum/fonts" / f"RetroBoot-{name}.bdf").read_text()
        glyphs = {}
        for block in source.split("STARTCHAR ")[1:]:
            code = int(re.search(r"ENCODING (\d+)", block)[1])
            advance = int(re.search(r"DWIDTH (\d+)", block)[1])
            box = list(map(int, re.search(r"BBX (\d+) (\d+) (-?\d+) (-?\d+)", block).groups()))
            rows = block.split("BITMAP\n")[1].split("ENDCHAR")[0].split()
            glyphs[code] = [advance, *box, rows]
        fonts[key] = glyphs
    return "// Generated by scripts/export-platinum.py from the Mac PlatinumKit and BDF sources.\n" + "export const measured = " + json.dumps(tables, separators=(",", ":")) + ";\nexport const fonts = " + json.dumps(fonts, separators=(",", ":")) + ";\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "desktop/ui/platinum-assets.mjs"
    result = export()
    if args.check:
        if not destination.exists() or destination.read_text() != result:
            raise SystemExit("Desktop Platinum assets are stale. Run desktop/scripts/export-platinum.py")
    else:
        destination.write_text(result)
